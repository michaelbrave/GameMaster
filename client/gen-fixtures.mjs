/**
 * Generates client/src/Fixtures.elm from contracts/fixtures so the Elm app
 * can run in an offline, fixture-backed mode (?fixtures=1). The fixtures are
 * real engine output (see server/src/fixtures/dumpFixtures.ts).
 *
 * Usage: node gen-fixtures.mjs   (from client/)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const FIXTURES = resolve(process.cwd(), "../contracts/fixtures");
const load = (name) => JSON.parse(readFileSync(resolve(FIXTURES, name), "utf8"));

const elmString = (value) => JSON.stringify(JSON.stringify(value));

const module_ = `module Fixtures exposing (..)

{-| Bundled fixture payloads for the offline fixture-backed mode.
GENERATED by gen-fixtures.mjs from contracts/fixtures — do not edit by hand.
-}

import Json.Encode as Encode


sessionStateJson : String
sessionStateJson =
    ${elmString(load("session-state.json"))}


mapJson : String
mapJson =
    ${elmString(load("map.json"))}


historyJson : String
historyJson =
    ${elmString(load("history.json"))}


tablesJson : String
tablesJson =
    ${elmString(load("tables.json"))}


travelEncounterJson : String
travelEncounterJson =
    ${elmString(load("command-response-travel-encounter.json"))}


actionJson : String
actionJson =
    ${elmString(load("command-response-action.json"))}


hexDetailJson : String
hexDetailJson =
    ${elmString(load("hex-detail.json"))}


unused : Encode.Value
unused =
    Encode.null
`;

writeFileSync(resolve(process.cwd(), "src/Fixtures.elm"), module_);
console.log("wrote src/Fixtures.elm");
